def text_files() -> list[Path]:
    return [
        path
        for path in sorted(SRC.rglob("*"))
        if path.is_file() and path.suffix in {".ts", ".tsx", ".css"}
    ]


def source_text() -> str:
    return "\n".join(path.read_text(encoding="utf-8", errors="ignore") for path in text_files())


