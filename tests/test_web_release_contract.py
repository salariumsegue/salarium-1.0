def test_literal_internal_links_target_governed_destinations() -> None:
    violations: list[str] = []
    pattern = re.compile(r'(?:href|canonical)\s*[:=]\s*(?:\{\s*)?["\'](/[^"\']*)["\']')
    for path in text_files():
        text = path.read_text(encoding="utf-8", errors="ignore")
        for match in pattern.finditer(text):
            href = match.group(1).split("?", 1)[0].split("#", 1)[0] or "/"
            if href not in ALLOWED_INTERNAL:
                violations.append(f"{path.relative_to(ROOT)} -> {match.group(1)}")
    assert not violations, "Unresolved internal links:\n" + "\n".join(violations)


def test_every_button_has_a_real_click_handler() -> None:
    violations: list[str] = []
    pattern = re.compile(r"<button\b[^>]*>", flags=re.DOTALL)
    for path in text_files():
        text = path.read_text(encoding="utf-8", errors="ignore")
        for match in pattern.finditer(text):
            if "onClick=" not in match.group(0):
                violations.append(f"{path.relative_to(ROOT)}: {match.group(0)[:140]}")
    assert not violations, "Buttons without handlers:\n" + "\n".join(violations)


